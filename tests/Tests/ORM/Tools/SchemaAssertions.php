<?php

declare(strict_types=1);

namespace Doctrine\Tests\ORM\Tools;

use Doctrine\DBAL\Schema\Column;
use Doctrine\DBAL\Schema\ForeignKeyConstraint;
use Doctrine\DBAL\Schema\Index as DbalIndex;
use Doctrine\DBAL\Schema\Index\IndexedColumn;
use Doctrine\DBAL\Schema\Name\UnqualifiedName;
use Doctrine\DBAL\Schema\PrimaryKeyConstraint;
use Doctrine\DBAL\Schema\PrimaryKeyConstraintEditor;
use Doctrine\DBAL\Schema\Table as DbalTable;
use Doctrine\DBAL\Types\Type;

use function array_key_exists;
use function array_map;
use function class_exists;
use function ksort;
use function method_exists;
use function sprintf;
use function strcasecmp;

/**
 * Cross-version assertions on DBAL schema objects.
 *
 * Asserting the generated schema rather than rendered SQL keeps tests independent
 * of DBAL's SQL formatting, which changes between minor versions.
 */
trait SchemaAssertions
{
    private static function assertTableEquals(DbalTable $expected, DbalTable $actual): void
    {
        self::assertEquals(
            self::toComparableTable($expected),
            self::toComparableTable($actual),
            sprintf('Table "%s" does not match the expected schema.', self::objectName($actual)),
        );
    }

    /**
     * Creates a table as generated by SchemaTool.
     *
     * @param list<Column>               $columns
     * @param list<string>               $primaryKey
     * @param list<DbalIndex>            $indexes
     * @param list<ForeignKeyConstraint> $foreignKeys
     * @param array<string, mixed>       $options
     */
    private static function table(
        string $name,
        array $columns,
        array $primaryKey = [],
        array $indexes = [],
        array $foreignKeys = [],
        array $options = [],
    ): DbalTable {
        if ($options === []) {
            $options = self::defaultTableOptions();
        }

        $table = new DbalTable($name, $columns, $indexes, [], $foreignKeys, $options);

        if ($primaryKey !== []) {
            if (method_exists($table, 'edit')) {
                $table = $table->edit()
                    ->addPrimaryKeyConstraint(
                        PrimaryKeyConstraint::editor()
                            ->setUnquotedColumnNames(...$primaryKey)
                            ->create(),
                    )
                    ->create();
            } else {
                $table->setPrimaryKey($primaryKey);
            }
        }

        return $table;
    }

    /**
     * Creates a column as generated by SchemaTool for a regular field.
     *
     * @param array<string, mixed> $options
     */
    private static function column(string $name, string $type, array $options = []): Column
    {
        if (! array_key_exists('platformOptions', $options)) {
            $options['platformOptions'] = ['version' => false];
        }

        return self::createColumn($name, $type, $options);
    }

    /**
     * Creates a column as generated by SchemaTool for a join column.
     *
     * @param array<string, mixed> $options
     */
    private static function joinColumn(string $name, string $type, array $options = []): Column
    {
        return self::createColumn($name, $type, ['platformOptions' => []] + $options);
    }

    /** @param list<string> $localColumns @param list<string> $foreignColumns */
    private static function foreignKey(
        array $localColumns,
        string $foreignTableName,
        array $foreignColumns,
    ): ForeignKeyConstraint {
        return new ForeignKeyConstraint($localColumns, $foreignTableName, $foreignColumns);
    }

    /** @return list<string> */
    private static function primaryKeyColumns(DbalTable $table): array
    {
        if (class_exists(PrimaryKeyConstraintEditor::class)) {
            $constraint = $table->getPrimaryKeyConstraint();
            self::assertNotNull($constraint);

            return array_map(
                static fn (UnqualifiedName $name): string => $name->toString(),
                $constraint->getColumnNames(),
            );
        }

        $primaryKeyIndex = $table->getPrimaryKey();
        self::assertNotNull($primaryKeyIndex);

        return self::indexColumnNames($primaryKeyIndex);
    }

    /** @return array<string, mixed> */
    private static function toComparableTable(DbalTable $table): array
    {
        $columns = [];
        foreach ($table->getColumns() as $column) {
            $columns[self::objectName($column)] = self::toComparableColumn($column);
        }

        ksort($columns);

        $indexes = [];
        foreach ($table->getIndexes() as $name => $index) {
            if (strcasecmp($name, 'primary') === 0) {
                continue;
            }

            $indexes[$name] = self::toComparableIndex($index);
        }

        ksort($indexes);

        $foreignKeys = [];
        foreach ($table->getForeignKeys() as $name => $foreignKey) {
            $foreignKeys[$name] = self::toComparableForeignKey($foreignKey);
        }

        ksort($foreignKeys);

        $options = $table->getOptions();
        ksort($options);

        return [
            'name'        => self::objectName($table),
            'columns'     => $columns,
            'primaryKey'  => self::primaryKeyColumns($table),
            'indexes'     => $indexes,
            'foreignKeys' => $foreignKeys,
            'options'     => $options,
        ];
    }

    /** @return array<string, mixed> */
    private static function toComparableIndex(DbalIndex $index): array
    {
        if (method_exists($index, 'getType')) {
            return [
                'name'      => self::objectName($index),
                'columns'   => self::indexColumnNames($index),
                'type'      => $index->getType()->name,
                'clustered' => $index->isClustered(),
                'predicate' => $index->getPredicate(),
            ];
        }

        return [
            'name'    => self::objectName($index),
            'columns' => self::indexColumnNames($index),
            'unique'  => $index->isUnique(),
            'flags'   => $index->getFlags(),
            'options' => $index->getOptions(),
        ];
    }

    /** @return array<string, mixed> */
    private static function toComparableForeignKey(ForeignKeyConstraint $foreignKey): array
    {
        if (method_exists($foreignKey, 'getReferencingColumnNames')) {
            return [
                'columns'        => array_map(
                    static fn (UnqualifiedName $columnName): string => $columnName->toString(),
                    $foreignKey->getReferencingColumnNames(),
                ),
                'foreignTable'   => $foreignKey->getReferencedTableName()->toString(),
                'foreignColumns' => array_map(
                    static fn (UnqualifiedName $columnName): string => $columnName->toString(),
                    $foreignKey->getReferencedColumnNames(),
                ),
                'options'        => [
                    'match'         => $foreignKey->getMatchType()->value,
                    'onUpdate'      => $foreignKey->getOnUpdateAction()->value,
                    'onDelete'      => $foreignKey->getOnDeleteAction()->value,
                    'deferrability' => $foreignKey->getDeferrability()->value,
                ],
            ];
        }

        $options = $foreignKey->getOptions();
        if (($options['deferrable'] ?? null) === false) {
            unset($options['deferrable']);
        }

        if (($options['deferred'] ?? null) === false) {
            unset($options['deferred']);
        }

        return [
            'columns'        => $foreignKey->getLocalColumns(),
            'foreignTable'   => $foreignKey->getForeignTableName(),
            'foreignColumns' => $foreignKey->getForeignColumns(),
            'options'        => $options,
        ];
    }

    /** @return array<string, mixed> */
    private static function toComparableColumn(Column $column): array
    {
        return [
            'type'             => method_exists($column, 'getTypeName')
                ? $column->getTypeName()
                : Type::getTypeRegistry()->lookupName($column->getType()),
            'length'           => $column->getLength(),
            'precision'        => $column->getPrecision(),
            'scale'            => $column->getScale(),
            'unsigned'         => $column->getUnsigned(),
            'fixed'            => $column->getFixed(),
            'notnull'          => $column->getNotnull(),
            'default'          => $column->getDefault(),
            'autoincrement'    => $column->getAutoincrement(),
            'platformOptions'  => $column->getPlatformOptions(),
            'columnDefinition' => $column->getColumnDefinition(),
            'comment'          => $column->getComment(),
        ];
    }

    /** @return array<string, mixed> */
    private static function defaultTableOptions(): array
    {
        return [
            'charset'   => 'utf8mb4',
            'collation' => 'utf8mb4_unicode_ci',
            'engine'    => 'InnoDB',
        ];
    }

    /** @param array<string, mixed> $options */
    private static function createColumn(string $name, string $type, array $options): Column
    {
        if (method_exists(Column::class, 'getTypeName')) {
            return new Column($name, $type, $options);
        }

        return new Column($name, Type::getType($type), $options);
    }

    /** @return list<string> */
    private static function indexColumnNames(DbalIndex $index): array
    {
        if (method_exists(DbalIndex::class, 'getIndexedColumns')) {
            return array_map(
                static fn (IndexedColumn $indexedColumn): string => $indexedColumn->getColumnName()->toString(),
                $index->getIndexedColumns(),
            );
        }

        return $index->getColumns();
    }

    private static function objectName(Column|DbalIndex|DbalTable $object): string
    {
        if (method_exists($object, 'getObjectName')) {
            $name = $object->getObjectName();

            if ($name instanceof UnqualifiedName) {
                return $name->getIdentifier()->getValue();
            }

            return $name->toString();
        }

        return $object->getName();
    }
}
